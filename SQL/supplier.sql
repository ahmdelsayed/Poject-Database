-- =============================================
-- Classify suppliers based on their name
-- =============================================
SELECT 
    name,
    contact,
    desc_info,
    CASE 
        WHEN name LIKE '%Technologies%' OR name LIKE '%Electronics%' OR name LIKE '%Apple%' OR name LIKE '%Samsung%' OR name LIKE '%LG%' THEN 'Electronics'
        WHEN name LIKE '%IKEA%' OR name LIKE '%Carrefour%' OR name LIKE '%Zara%' OR name LIKE '%Nike%' THEN 'Retail & Fashion'
        ELSE 'General Supplier'
    END AS supplier_category
FROM supplier;

-- =============================================
-- Find the highest and lowest invoice numbers
-- =============================================
SELECT 
    MAX(invoice) AS Highest_Invoice,
    MIN(invoice) AS Lowest_Invoice
FROM supplier;

-- =============================================
-- Show suppliers that contain 'Official supplier' in description
-- =============================================
SELECT * FROM supplier 
WHERE desc_info LIKE '%Official supplier%';

-- =============================================
-- Count how many suppliers per category
-- =============================================
SELECT 
    CASE 
        WHEN name LIKE '%Technologies%' OR name LIKE '%Electronics%' OR name LIKE '%Apple%' OR name LIKE '%Samsung%' OR name LIKE '%LG%' THEN 'Electronics'
        WHEN name LIKE '%IKEA%' OR name LIKE '%Carrefour%' OR name LIKE '%Zara%' OR name LIKE '%Nike%' THEN 'Retail & Fashion'
        ELSE 'General Supplier'
    END AS supplier_category,
    COUNT(*) AS Total
FROM supplier
GROUP BY 
    CASE 
        WHEN name LIKE '%Technologies%' OR name LIKE '%Electronics%' OR name LIKE '%Apple%' OR name LIKE '%Samsung%' OR name LIKE '%LG%' THEN 'Electronics'
        WHEN name LIKE '%IKEA%' OR name LIKE '%Carrefour%' OR name LIKE '%Zara%' OR name LIKE '%Nike%' THEN 'Retail & Fashion'
        ELSE 'General Supplier'
    END
ORDER BY Total DESC;