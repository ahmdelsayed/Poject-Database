-- =============================================
-- Categories that start with 'M'
-- =============================================
SELECT * FROM category 
WHERE name LIKE 'M%';

-- =============================================
-- Categories containing 'Phone' or 'Laptop'
-- =============================================
SELECT * FROM category 
WHERE name LIKE '%Phone%' OR name LIKE '%Laptop%';

-- =============================================
-- Count total number of categories
-- =============================================
SELECT COUNT(*) AS Total_Categories FROM category;

-- =============================================
-- Count occurrences of each category name (to see duplicates)
-- =============================================
SELECT name, COUNT(*) AS Count
FROM category
GROUP BY name
ORDER BY Count DESC;

-- =============================================
-- Top 10 most repeated category names
-- =============================================
SELECT TOP 10 name, COUNT(*) AS Count
FROM category
GROUP BY name
ORDER BY Count DESC;

-- =============================================
-- Categories with more than 5 occurrences
-- =============================================
SELECT name, COUNT(*) AS Count
FROM category
GROUP BY name
HAVING COUNT(*) > 5
ORDER BY Count DESC;

-- =============================================
-- Search for Electronics related categories
-- =============================================
SELECT * FROM category 
WHERE name LIKE '%Electronic%' OR name LIKE '%Mobile%';

-- =============================================
-- Classify categories (example using CASE)
-- =============================================
SELECT 
    name,
    CASE 
        WHEN name LIKE '%Mobile%' OR name LIKE '%Phone%' THEN 'Mobile Devices'
        WHEN name LIKE '%Laptop%' OR name LIKE '%Computer%' THEN 'Computing'
        WHEN name LIKE '%Home%' THEN 'Home Appliances'
        WHEN name LIKE '%Furniture%' THEN 'Furniture'
        WHEN name LIKE '%Clothing%' THEN 'Fashion'
        ELSE 'Other'
    END AS category_type
FROM category;

-- =============================================
-- Count categories per type (using the classification above)
-- =============================================
SELECT 
    CASE 
        WHEN name LIKE '%Mobile%' OR name LIKE '%Phone%' THEN 'Mobile Devices'
        WHEN name LIKE '%Laptop%' OR name LIKE '%Computer%' THEN 'Computing'
        WHEN name LIKE '%Home%' THEN 'Home Appliances'
        WHEN name LIKE '%Furniture%' THEN 'Furniture'
        WHEN name LIKE '%Clothing%' THEN 'Fashion'
        ELSE 'Other'
    END AS category_type,
    COUNT(*) AS Total
FROM category
GROUP BY 
    CASE 
        WHEN name LIKE '%Mobile%' OR name LIKE '%Phone%' THEN 'Mobile Devices'
        WHEN name LIKE '%Laptop%' OR name LIKE '%Computer%' THEN 'Computing'
        WHEN name LIKE '%Home%' THEN 'Home Appliances'
        WHEN name LIKE '%Furniture%' THEN 'Furniture'
        WHEN name LIKE '%Clothing%' THEN 'Fashion'
        ELSE 'Other'
    END
ORDER BY Total DESC;

-- =============================================
-- Show all categories sorted alphabetically
-- =============================================
